/** URL "icons/…" d'un rôle, ou "" si la table ne le connaît pas.
 *  Un nom de fichier (nodes_box.svg, fs_sketch.svg, icons/fs_sketch.svg)
 *  est ramené à son rôle : le moteur envoie encore des noms de fichiers. */
export function iconSrc(role) {
  const key = roleKey(role);
  const file = key ? ICONS[key] : undefined;
  return file ? "icons/" + file : "";
}

function roleKey(value) {
  if (typeof value !== "string") return "";
  let name = value.trim();
  if (!name || name.includes("..") || name.includes("\\") || name.includes(":")) {
    return "";
  }
  if (name.startsWith("icons/")) name = name.slice("icons/".length);
  if (name.endsWith(".svg")) name = name.slice(0, -4);
  if (name.startsWith("fs_")) name = name.slice(3);
  if (!/^[A-Za-z0-9_-]+$/.test(name)) return "";
  return name;
}

/** Pose src sur les images déclarées par data-icon (le HTML ne nomme aucun fichier). */
export function applyStaticIcons(root) {
  if (!root || typeof root.querySelectorAll !== "function") return;
  for (const img of root.querySelectorAll("img[data-icon]")) {
    const src = iconSrc(img.dataset.icon);
    if (src) img.src = src;
  }
}
